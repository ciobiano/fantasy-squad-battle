// Generates the app's design tokens from design/tokens.json, the Design System's
// token file (https://claude.ai/artifact/8hkdZjwZq7JvCU4FS7NzYi). Run `npm run tokens`
// after copying a new tokens.json from the Design System.
//
// Outputs:
// - app/tokens.css: CSS variables (light by default, dark by system preference or
//   data-theme="dark", light forced by data-theme="light") plus the Tailwind mapping.
// - lib/tokens.ts: the same colours as plain values, for next/og cards, which can't
//   read CSS variables.
import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const source = JSON.parse(await readFile(new URL("design/tokens.json", root), "utf8"));

const colours = source.color.tokens;
const gradients = source.gradient.tokens;
const radii = source.radius.tokens;

// "{ink}" in the token file means "the value of ink".
const resolve = (value, theme) => {
  const match = /^\{([a-z0-9-]+)\}$/.exec(value);
  if (!match) return value;
  const target = colours.find((token) => token.name === match[1]);
  if (!target) throw new Error(`Unknown token reference ${value}`);
  return resolve(typeof target.value === "string" ? target.value : target.value[theme], theme);
};
const valueFor = (token, theme) =>
  resolve(typeof token.value === "string" ? token.value : token.value[theme], theme);

const declarations = (theme, { themedOnly }) =>
  colours
    .filter((token) => !themedOnly || typeof token.value !== "string")
    .map((token) => `  --${token.name}: ${valueFor(token, theme)};`)
    .concat([`  --gradient-sky: var(--gradient-sky-${theme});`])
    .join("\n");

const header = "/* Generated by scripts/build-tokens.mjs from design/tokens.json. Don't edit by hand. */";

const css = `${header}

:root {
  color-scheme: light;
${declarations("light", { themedOnly: false })}
${gradients.map((token) => `  --${token.name}: ${token.value};`).join("\n")}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${declarations("dark", { themedOnly: true }).replace(/^/gm, "  ")}
  }
}

:root[data-theme="dark"],
[data-theme="dark"] {
  color-scheme: dark;
${declarations("dark", { themedOnly: true })}
}

[data-theme="light"] {
  color-scheme: light;
${declarations("light", { themedOnly: true })}
}

@theme inline {
${colours.map((token) => `  --color-${token.name}: var(--${token.name});`).join("\n")}
${radii.map((token) => `  --${token.name}: ${token.value};`).join("\n")}
}
`;

const toTs = (theme) =>
  colours.map((token) => `    ${JSON.stringify(token.name)}: ${JSON.stringify(valueFor(token, theme))},`).join("\n");

const ts = `${header.replace("/*", "//").replace(" */", "")}

export const colours = {
  dark: {
${toTs("dark")}
  },
  light: {
${toTs("light")}
  },
} as const;

export type Theme = keyof typeof colours;
export type ColourName = keyof (typeof colours)["dark"];

export const gradients = {
${gradients.map((token) => `  ${JSON.stringify(token.name)}: ${JSON.stringify(token.value)},`).join("\n")}
} as const;
`;

await writeFile(new URL("app/tokens.css", root), css);
await writeFile(new URL("lib/tokens.ts", root), ts);
console.log(`tokens: ${colours.length} colours, ${gradients.length} gradients, ${radii.length} radii`);
